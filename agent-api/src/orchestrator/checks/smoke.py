def custom_operations(plan: dict[str, Any]) -> list[dict[str, Any]]:
    """The planned operations the templates did not write (custom ones; aggregates are templated, and checked too)."""
    from ..backend.codegen import is_crud

    return [
        op
        for module in plan.get("modules", [])
        if not module.get("plugin")  # a plugin's operations come with their own scenarios
        for op in module.get("operations", [])
        if not is_crud(op)
    ]


def sample_value(contract: dict[str, Any], schema: Any, record: dict[str, Any] | None = None, depth: int = 0) -> Any:
    """A value the schema admits, taking fields from `record` (a fixture) where their names match."""
    from ..integration.contract import resolve

    schema = resolve(contract, schema) if isinstance(schema, dict) else {}
    if depth > 5 or not isinstance(schema, dict):
        return None
    for key in ("anyOf", "oneOf"):
        options = [
            option for option in schema.get(key) or [] if (resolve(contract, option) or {}).get("type") != "null"
        ]
        if options:
            return sample_value(contract, options[0], record, depth + 1)
    if schema.get("enum"):
        return next((value for value in schema["enum"] if value is not None), None)
    types, _ = _types(contract, schema)
    kind = next((t for t in ("object", "array", "string", "integer", "number", "boolean") if t in types), None)
    if kind == "object":
        record = record or {}
        properties = schema.get("properties") or {}
        out = {}
        for name in schema.get("required") or []:
            out[name] = (
                record[name] if name in record else sample_value(contract, properties.get(name), None, depth + 1)
            )
        for name, value in record.items():
            if name in properties and name not in out and name != "id":
                out[name] = value
        return out
    if kind == "array":
        return []
    if kind == "string":
        fmt = schema.get("format")
        return {
            "date": SAMPLE_DATE,
            "date-time": SAMPLE_DATETIME,
            "uuid": SAMPLE_UUID,
            "email": "smoke@example.com",
        }.get(fmt, "Sample")
    if kind in ("integer", "number"):
        low = schema.get("minimum", schema.get("exclusiveMinimum", 0))
        value = max(1, int(low) + (1 if "exclusiveMinimum" in schema else 0))
        return value if kind == "integer" else float(value)
    if kind == "boolean":
        return True
    return None


def resolve_operation_path(path: str, operation: dict[str, Any], contract: dict[str, Any]) -> str | None:
    """`path` with its parameters from the first fixture of the operation's entity (None: no fixture fills it)."""
    params = _PATH_PARAM.findall(path)
    if not params:
        return path
    entity = (operation.get("x-bga") or {}).get("entity")
    fixtures = ((contract.get("x-bga") or {}).get("fixtures") or {}).get(entity) or []
    if not fixtures:
        return None
    record = fixtures[0]
    resolved = path
    for param in params:
        val = record.get(param) or record.get("id")
        if val is None:
            return None
        resolved = resolved.replace(f"{{{param}}}", str(val))
    return resolved


def smoke_calls(contract: dict[str, Any], plan: dict[str, Any]) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """(calls, skipped): one call per endpoint. An operation with scenarios runs its first success scenario; a custom
    operation without one gets path parameters from the first fixture of its entity and a request body built from its
    request schema and that fixture. Operations behind auth with no way to sign in, or whose path cannot be filled,
    are skipped (named, so the result says so)."""
    from ..integration.contract import contract_operations, resolve

    operations = contract_operations(contract)
    fixtures = (contract.get("x-bga") or {}).get("fixtures") or {}
    refs = {
        f"{name[:1].lower()}{name[1:]}Id": rows[0]["id"]
        for name, rows in fixtures.items()
        if rows and isinstance(rows[0], dict) and "id" in rows[0]
    }
    calls, skipped = scenario_calls(contract)
    calls = one_per_operation(calls)
    called = {call["operationId"] for call in calls}
    for op in custom_operations(plan):
        entry = operations.get(op["operationId"])
        if entry is None or op["operationId"] in called:
            continue
        operation = entry["operation"]
        if operation.get("security") and smoke_login(contract) is None:
            skipped.append({"operation": op["operationId"], "reason": "needs auth"})
            continue
        path = resolve_operation_path(entry["path"], operation, contract)
        if path is None:
            skipped.append({"operation": op["operationId"], "reason": "no fixture for its path parameters"})
            continue
        entity = (operation.get("x-bga") or {}).get("entity")
        record = (fixtures.get(entity) or [None])[0] or {}
        # `bookingId`, `timeSlotId`: a seeded record's id. A create (no path parameters) gets fresh references
        # rather than the seeded record's own, which its rules would reject as a duplicate.
        if entry["method"].lower() == "post" and "{" not in entry["path"]:
            record = record | refs
        else:
            record = refs | record
        body = None
        request = ((operation.get("requestBody") or {}).get("content") or {}).get("application/json")
        if request and request.get("schema"):
            body = sample_value(contract, resolve(contract, request["schema"]), record)
        call = {"operationId": op["operationId"], "method": entry["method"], "path": path, "body": body}
        if operation.get("security"):
            call["auth"] = True
        calls.append(call)
    webhooks = plan.get("webhooks") or {}
    if webhooks.get("outgoing"):  # Story 10.8: a subscription the worker delivers a signed ping to
        admin = next((u["login"] for u in (plan.get("auth") or {}).get("demoUsers", []) if u["role"] == "admin"), None)
        calls.append({"operationId": "webhooks.subscribe", "kind": "webhook_subscribe", "method": "POST",
                      "path": "/webhooks/subscriptions", "event": webhooks["outgoing"][0], "auth": True,
                      **({"user": admin} if webhooks.get("access") == "role" and admin else {})})  # fmt: skip
    payable = ((contract.get("x-bga") or {}).get("payments") or {}).get("payable")
    if plan.get("payments") and payable is not None:  # Story 10.9: a seeded record paid on the fake page
        path = plan["payments"]["path"].replace("{recordId}", quote(str(payable), safe=""))
        calls.append({"operationId": "payments.checkout", "kind": "payment_pay", "method": "POST", "path": path,
                      "auth": True})  # fmt: skip
    if plan.get("jobs"):  # last: the worker runs what the calls enqueued, and must not crash (Story 10.6)
        calls.append({"operationId": "jobs.worker", "kind": "worker", "method": "RUN", "path": "src.worker --once"})
    return calls, skipped


def one_per_operation(calls: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """The first success scenario of each operation (else its first scenario), in contract order. The expected answer
    is dropped: any answer that is not a server error passes."""
    chosen: dict[str, dict[str, Any]] = {}
    for call in calls:
        op_id = call["operationId"]
        success = str((call.get("expect") or {}).get("status", "")).startswith("2")
        if op_id not in chosen or (success and not chosen[op_id]["success"]):
            chosen[op_id] = {"call": call, "success": success}
    return [{k: v for k, v in item["call"].items() if k != "expect"} for item in chosen.values()]


def smoke_login(contract: dict[str, Any]) -> dict[str, Any] | None:
    """Story 10.2: how the smoke script signs in (a seeded demo user), when the contract has auth."""
    return ((contract.get("x-bga") or {}).get("auth") or {}).get("login")


def scenario_calls(contract: dict[str, Any]) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Story 10.0b: one call per contract scenario, with what it must answer. Operations behind auth run with the
    smoke user's token (10.2), or are skipped when the contract has no way to sign in."""
    from ..integration.contract import contract_operations

    signed_in = smoke_login(contract) is not None
    calls, skipped = [], []
    for op_id, entry in contract_operations(contract).items():
        operation = entry["operation"]
        scenarios = (operation.get("x-bga") or {}).get("scenarios") or []
        if scenarios and operation.get("security") and not signed_in:
            skipped.append({"operation": op_id, "reason": "needs auth"})
            continue
        for scenario in scenarios:
            path = entry["path"]
            for name, value in scenario["params"].items():
                path = path.replace(f"{{{name}}}", quote(str(value), safe=""))
            calls.append(
                {
                    "operationId": op_id,
                    "method": entry["method"],
                    "path": path,
                    "body": scenario.get("body"),
                    "scenario": scenario["name"],
                    "expect": scenario["expect"],
                    "auth": scenario.get("auth", bool(operation.get("security"))),
                    **({"user": scenario["user"]} if scenario.get("user") else {}),
                }
            )
    return calls, skipped


def judge(contract: dict[str, Any], calls: list[dict[str, Any]], answers: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Failures (operation, request, response): an endpoint that answered a server error (5xx) or nothing, and a job
    worker run that crashed. Any 2xx or 4xx is an answer: who may call what, and which requests the rules accept, is
    the app's business, not this check's."""
    problems: list[dict[str, Any]] = []
    for call, answer in zip(calls, answers, strict=False):
        op_id = call["operationId"]
        status = answer.get("status")
        text = str(answer.get("body") or "")
        if call.get("kind") == "worker":  # Story 10.6: the jobs the calls enqueued ran without crashing
            if status != 0:
                message = "the job worker failed (`python -m src.worker --once`)"
                problems.append({"operation": op_id, "message": message, "request": call["path"],
                                 "response": text[-600:]})  # fmt: skip
            continue
        if isinstance(status, int) and 0 < status < 500:
            continue
        what = STEPS.get(call.get("kind") or "") or op_id
        request = f"{call['method']} {call['path']}" + (
            f" {json.dumps(call['body'])[:300]}" if call.get("body") else ""
        )
        got = f"HTTP {status}" if status else "no response"
        problems.append({"operation": op_id, "message": f"{what}: {got}", "request": request, "response": text[-600:]})
    return problems
