"""Engine-written view slots (Epic 23, Story 23.11): an opt-in experiment, off by default (`APP_VIEW_SLOTS=off`,
decision D8). With it on, the code engine writes the app's shell and its main records' cards against fixed props
(`src/components/app/slot-types.ts`); data, forms, auth, mocks and `lib/api` stay the kit's. A slot that calls the API,
renders a form or has no default export is refused and the kit's view is used (a note says so).

The registry `src/components/app/slots.ts` (generator-owned) names the accepted slots; the kit reads it.
"""

import json
import re
from dataclasses import dataclass, field
from typing import Any

from src.configs import config
from src.modules.shared.domain.frontend_spec.design_registry import registry

SLOTS_DIR = "src/components/app/slots"
REGISTRY = "src/components/app/slots.ts"
SLOT_INPUT = ".bga/slot.json"  # what the slot's engine call is asked to write (the fake engine reads it too)
CARD_VIEWS = registry().tagged("list-view", "cards")  # Epic 30: the list views laid out as cards
MAX_CARDS = 3  # the main entity's card and up to two more
# Things a slot may not do: the kit's data layer, forms and the network belong to tested code (Story 23.11).
FORBIDDEN = (
    (re.compile(r"\bfetch\s*\("), "calls fetch"),
    (re.compile(r"@/lib/api"), "imports the API client"),
    (re.compile(r"\b(useOperationQuery|useOperationMutation|useQuery|useMutation)\b"), "loads or changes data"),
    (re.compile(r"<form\b"), "renders a form"),
    (re.compile(r"localStorage|sessionStorage|document\.cookie"), "reads storage"),
)


@dataclass
class Slot:
    name: str  # `Shell`, or `<Entity>Card`
    kind: str  # "shell" | "card"
    file: str
    entity: str | None = None
    brief: dict[str, Any] = field(default_factory=dict)


@dataclass
class SlotOutcome:
    slot: Slot
    accepted: bool
    reason: str | None = None


def enabled(options: dict[str, Any] | None) -> bool:
    """The generation's `options.viewSlots`, else `APP_VIEW_SLOTS`; only `engine` turns slots on."""
    value = (options or {}).get("viewSlots") or config.app_view_slots
    return value == "engine"


def planned_slots(spec: dict[str, Any]) -> list[Slot]:
    """The shell, then a card per entity shown as cards, a media grid or a feed (the main entity first)."""
    design = (spec.get("app") or {}).get("design") or {}
    out = [
        Slot(
            "Shell",
            "shell",
            f"{SLOTS_DIR}/Shell.tsx",
            brief={k: design.get(k) for k in ("archetype", "shell", "recipe")},
        )
    ]
    entities = design.get("entities") or {}
    order = [design.get("mainEntity"), *sorted(entities)]
    for entity in dict.fromkeys(name for name in order if name):
        view = entities.get(entity) or {}
        if view.get("view") in CARD_VIEWS and len(out) <= MAX_CARDS:
            out.append(
                Slot(
                    f"{entity}Card",
                    "card",
                    f"{SLOTS_DIR}/{entity}Card.tsx",
                    entity,
                    {"view": view["view"], "roles": view.get("roles") or {}},
                )
            )
    return out


def refusal(text: str) -> str | None:
    """Why a slot's code is refused, or None."""
    if not re.search(r"export\s+default\s+function\b|export\s+default\s+\w+", text):
        return "has no default export"
    for pattern, why in FORBIDDEN:
        if pattern.search(text):
            return why
    return None


def registry_ts(accepted: list[Slot]) -> str:
    """`slots.ts`: the accepted slots by place (an empty registry: the kit's views everywhere)."""
    imports = "".join(f'import {slot.name} from "./slots/{slot.name}";\n' for slot in accepted)
    shell = next((slot.name for slot in accepted if slot.kind == "shell"), "undefined")
    cards = ", ".join(f"{json.dumps(slot.entity)}: {slot.name}" for slot in accepted if slot.kind == "card")
    return (
        "// Generated by the Fullstack Generation Agent (Story 23.11): the engine-written view slots in use.\n"
        'import type { TSlots } from "./slot-types";\n'
        + imports
        + f"\nexport const slots: TSlots = {{ shell: {shell}, cards: {{ {cards} }} }};\n"
    )


def slot_input(slot: Slot, spec: dict[str, Any]) -> dict[str, Any]:
    """What one slot's engine call gets (`.bga/slot.json`): its place, file, props type and the brief's choices."""
    app = spec.get("app") or {}
    entity = (app.get("entities") or {}).get(slot.entity or "") or {}
    return {
        "name": slot.name,
        "kind": slot.kind,
        "file": slot.file,
        "props": "TShellProps" if slot.kind == "shell" else "TCardProps",
        "entity": slot.entity,
        "labels": {k: entity.get(k) for k in ("label", "plural", "fieldLabels") if entity.get(k)},
        "brief": slot.brief,
        "appName": app.get("name"),
        "locale": (spec.get("project") or {}).get("locale") or "en",
    }
