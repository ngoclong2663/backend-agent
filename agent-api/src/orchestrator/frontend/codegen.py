def _route_order(path: str) -> tuple[tuple[int, str], ...]:
    """Sort key: at each segment a literal sorts before a parameter."""
    return tuple((1 if _PATH_PARAM.fullmatch(segment) else 0, segment) for segment in path.strip("/").split("/"))


