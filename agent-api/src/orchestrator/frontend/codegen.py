def mock_defaults(contract: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """Entity → the values its create request defaults (`status: PENDING`), which the mocks give a new record that
    leaves them out, as the backend's columns do (Story 22.7)."""
    out: dict[str, dict[str, Any]] = {}
    for found in contract_operations(contract).values():
        meta = found["operation"].get("x-bga") or {}
        if meta.get("action") != "create" or not meta.get("entity"):
            continue
        body = ((found["operation"].get("requestBody") or {}).get("content") or {}).get("application/json", {})
        properties = resolve(contract, body.get("schema") or {}).get("properties") or {}
        defaults = {name: prop["default"] for name, prop in properties.items() if prop.get("default") is not None}
        if defaults:
            out[meta["entity"]] = defaults
    return out


def mock_operations(contract: dict[str, Any]) -> list[dict[str, Any]]:
    """What the generic MSW handlers need per operation (`src/mocks/handlers.ts` reads this)."""
    fixtures = (contract.get("x-bga") or {}).get("fixtures") or {}
    schemas = contract.get("components", {}).get("schemas", {})
    planned = []
    # MSW matches handlers in order: a literal segment (`/classes/today`) must come before a parameter
    # (`/classes/:id`) at the same position, or the parameter answers it (404 for id "today").
    for op in sorted(_ops(contract), key=lambda op: _route_order(op.path)):
        query = {p["name"]: p for p in op.params if p["in"] == "query"}
        sort = (query.get("sort") or {}).get("schema", {}).get("enum") or []
        limit = (query.get("limit") or {}).get("schema", {})
        entity_schema = schemas.get(f"{op.entity}Response") or {}
        pk = (
            "id"
            if "id" in (entity_schema.get("properties") or {})
            else next(iter(entity_schema.get("properties") or {}), "id")
        )
        mock_plan = op.raw.get("x-bga", {}).get("mock")
        sample = op.raw.get("x-bga", {}).get("sample")
        # Story 23.4: a range's two parameters → the field and the bound the mocks apply
        bounds = {
            name: {"field": rng["field"], "bound": bound}
            for rng in op.raw.get("x-bga", {}).get("ranges") or []
            for name, bound in ((rng["from"], "gte"), (rng["to"], "lte"))
        }
        envelope = True
        resp2xx = next((r for s, r in sorted(op.raw.get("responses", {}).items()) if s.startswith("2")), {})
        content_schema = (resp2xx.get("content") or {}).get("application/json", {}).get("schema", {})
        if content_schema.get("type") == "array":
            envelope = False
        entry = {
            "operationId": op.id,
            "method": op.method,
            "path": _PATH_PARAM.sub(lambda m: f":{m.group(1)}", op.path),
            "entity": op.entity,
            "action": op.action,
            "mock": mock_plan,
            "sample": sample,
            "aggregate": op.raw.get("x-bga", {}).get("aggregate"),  # Epic 21: what the mock computes
            "envelope": envelope,
            "primaryKey": pk,
            "status": next((int(s) for s in sorted(op.raw.get("responses") or {}) if s.startswith("2")), 200),
            "filters": [name for name in query if name not in ("limit", "offset", "sort", "q") and name not in bounds],
            "sort": sorted({value.lstrip("-") for value in sort}),
            "search": "q" in query,
            "defaultLimit": limit.get("default", 20),
            "maxLimit": limit.get("maximum", 100),
            "hasFixtures": op.entity in fixtures,
        }
        if bounds:
            entry["ranges"] = bounds
        # Story 22.7: what the mocks check before answering, as the backend's plugins do
        meta = op.raw.get("x-bga") or {}
        if op.raw.get("security"):
            entry["secured"] = True
        if meta.get("policy"):
            entry["policy"] = meta["policy"]
        if meta.get("visibility"):  # Story 23.9: what a restricted caller may see, as the backend narrows it
            entry["visibility"] = {key: meta["visibility"][key] for key in ("roles", "where")}
        if meta.get("errors"):
            entry["errors"] = [
                {key: error[key] for key in ("status", "code", "message", "fields") if error.get(key) is not None}
                for error in meta["errors"]
            ]
        # Story 22.4: the request checks the API makes, so the mocks answer a bad request as the backend does
        body = ((op.raw.get("requestBody") or {}).get("content") or {}).get("application/json", {}).get("schema")
        if body:
            request = resolve(contract, body)
            references = {
                name: ((prop.get("x-bga") or {}).get("ref") or {}).get("entity")
                for name, prop in (request.get("properties") or {}).items()
                if (prop.get("x-bga") or {}).get("source") == "reference"
            }
            entry["required"] = list(request.get("required") or [])
            entry["references"] = {name: entity for name, entity in references.items() if entity}
        planned.append(entry)
    return planned


