def bindings_ts(contract: dict[str, Any] | None, app: bool = False) -> str:
    """Story 17.4: every operation by `operationId` (fetcher + the same query keys as `queries.ts`), behind two
    generic hooks the section library uses; empty in static mode."""
    ops = _ops(contract) if contract else []
    fetchers, keys, mutations = [], [], []
    for op in ops:
        params = f"params as {_params_type(op.function)}" if op.params else ""
        body = f"body as {op.request}" if op.request else ""
        call = f"{op.function}({', '.join(arg for arg in (params, body) if arg)})"
        if op.method == "GET":
            fetchers.append(f"  {_json(op.id)}: (params) => {call},\n")
            keys.append(f"  {_json(op.id)}: (params) => {op.query_key()},\n")
        else:
            mutations.append(
                f"  {_json(op.id)}: {{ run: (params, body) => {call}, "
                f"keys: {op.keys}.all, method: {_json(op.method)} }},\n"
            )
    imports = ""
    if ops:
        imports = (
            "import {\n" + "".join(f"  {op.function},\n" for op in ops) + '} from "@/lib/api/operations";\n'
            "import {\n"
            + "".join(f"  {k},\n" for k in sorted({op.keys for op in ops}))
            + '} from "@/lib/api/query-keys";\n'
        )
        used = "".join(fetchers + mutations)
        names = sorted(set(re.findall(r"\bas (T[A-Za-z0-9]+)", used)))
        if names:
            imports += "import type {\n" + "".join(f"  {name},\n" for name in names) + '} from "@/lib/api/types";\n'
    return (
        '"use client";\n\n'
        + HEADER
        + 'import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";\n'
        + imports
        + "\ntype TParams = Record<string, unknown>;\n"
        + "type TMutationVariables = { params: TParams; body: TParams };\n\n"
        + "const fetchers: Record<string, (params: TParams) => Promise<unknown>> = {\n"
        + "".join(fetchers)
        + "};\n\n"
        + "const queryKeys: Record<string, (params: TParams) => readonly unknown[]> = {\n"
        + "".join(keys)
        + "};\n\n"
        + "const mutations: Record<string, { run: (params: TParams, body: TParams) => Promise<unknown>; "
        + "keys: readonly unknown[]; method: string }> = {\n"
        + "".join(mutations)
        + "};\n\n"
        + (APP_FETCH if app else "")
        + "/** A data section's records: the operation's response (disabled without an operation). */\n"
        + "export function useOperationQuery(operationId: string | undefined, params: TParams) {\n"
        + "  const known = operationId !== undefined && operationId in fetchers;\n"
        + "  return useQuery({\n"
        + '    queryKey: known ? queryKeys[operationId](params) : ["no-operation"],\n'
        + "    queryFn: () => fetchers[operationId as string](params),\n"
        + "    enabled: known,\n"
        + "  });\n"
        + "}\n\n"
        + "/** A form's operation; on success the lists of the same resource refresh. */\n"
        + "export function useOperationMutation(operationId: string | undefined) {\n"
        + "  const queryClient = useQueryClient();\n"
        + "  const mutationMeta = operationId ? mutations[operationId] : undefined;\n"
        + "  const result = useMutation({\n"
        + "    mutationFn: ({ params, body }: TMutationVariables) => {\n"
        + "      // No operation: a client-only form. An unknown one is an error, never a silent success.\n"
        + "      if (operationId === undefined) return Promise.resolve({ success: true });\n"
        + "      if (!mutationMeta) return Promise.reject(new Error(`Unknown operation: ${operationId}`));\n"
        + "      return mutationMeta.run(params, body);\n"
        + "    },\n"
        + "    onSuccess: () => {\n"
        + "      if (mutationMeta) return queryClient.invalidateQueries({ queryKey: mutationMeta.keys });\n"
        + "    },\n"
        + "  });\n"
        + "  return Object.assign(result, { method: mutationMeta?.method });\n"
        + "}\n\n"
        + "/** operationId → filter parameter → the values it allows (from the contract's enums). */\n"
        + "export const filterOptions: Record<string, Record<string, string[]>> = "
        + json.dumps(filter_options(contract), indent=2, ensure_ascii=False)
        + ";\n"
    )


