def _label(field: str) -> str:
    words = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", field).replace("_", " ")
    return words[:1].upper() + words[1:].lower()


def _columns(data: dict[str, Any], records: list[dict[str, Any]]):
    """The fields a content section shows, labelled and formatted (images)."""
    fields = data.get("fields") or list(records[0] if records else {})
    columns = []
    for field in fields:
        column = {"key": field, "label": _label(field)}
        sample = records[0].get(field) if records else None
        format_ = None
        if isinstance(sample, str) and (sample.startswith("asset:") or sample.startswith("https://")):
            format_ = "image"
        if format_:
            column["format"] = format_
        columns.append(column)
    return columns


def icon_style(spec: dict[str, Any]) -> dict[str, str]:
    """The site's icon set, weight and treatment (Story 20.5), with the defaults filled in."""
    return DEFAULT_ICONS | {k: v for k, v in ((spec.get("theme") or {}).get("icons") or {}).items() if v}


def resolve_icons(value: Any, icon_set: str) -> Any:
    """A copy of section content or records with every item `icon` resolved to the site's set (`phosphor:Truck`);
    icons that resolve to nothing (or every icon, with the set `none`) are left out."""
    if isinstance(value, list):
        return [resolve_icons(item, icon_set) for item in value]
    if not isinstance(value, dict):
        return value
    out = {}
    for key, item in value.items():
        if key == "icon" and isinstance(item, str):
            resolved = resolve_icon(item, icon_set)
            if resolved:
                out[key] = resolved
        else:
            out[key] = resolve_icons(item, icon_set)
    return out


class _Site:
    def __init__(self, plan: dict[str, Any], spec: dict[str, Any], contract: dict[str, Any] | None):
        self.contract = contract
        self.icon_set = icon_style(spec)["set"]
        self.collections = {
            item["collection"]: resolve_icons(item["records"], self.icon_set) for item in spec.get("content", [])
        }
        self.spec = spec
        self.pages = {route["pageId"]: route["route"] for route in plan["routes"]}

    def tree(self, tree: dict[str, Any]) -> dict[str, Any]:
        return tree_site(tree, self.spec, self.contract, self.pages, self.icon_set, self.section)

    def section(self, section: dict[str, Any]) -> dict[str, Any]:
        out: dict[str, Any] = {"id": section["id"], "component": section["component"]}
        if section.get("content"):
            out["content"] = resolve_icons(section["content"], self.icon_set)
        data = section.get("data") or {}
        if data.get("kind") == "content":
            records = self.collections.get(data["collection"], [])
            out["data"] = {"collection": data["collection"], "columns": _columns(data, records)}
        if section.get("states"):
            out["states"] = section["states"]
        if section.get("form"):
            out["form"] = section["form"]
        if section.get("children"):
            out["children"] = [self.section(child) for child in section["children"]]
        return out


def _form(form: dict[str, Any]) -> dict[str, Any]:
    fields = [
        {k: field[k] for k in ("name", "type", "label", "required", "hidden", "value", "values", "placeholder")
         if field.get(k) is not None}
        for field in form["fields"]
    ]  # fmt: skip
    for field in fields:
        field.setdefault("type", "string")
        field.setdefault("label", _label(field["name"]))
    out = {
        "operationId": form.get("operationId"),
        "params": form.get("params") or {},
        "fields": fields,
        "submitLabel": form.get("submitLabel") or "Submit",
        "onSuccess": form.get("onSuccess") or {},
    }
    if form.get("load"):
        out["load"] = form["load"]
    return out


def section_props(
    plan: dict[str, Any], spec: dict[str, Any], contract: dict[str, Any] | None, section: dict[str, Any]
) -> dict[str, Any]:
    """The props `SectionRenderer.tsx` gives a section's component (without children): its content, its collection's
    records, columns and states. Used for a custom component's render test (17.3)."""
    site = _Site(plan, spec, contract)
    rendered = site.section({**section, "children": None})
    props = dict(rendered.get("content") or {})
    data = rendered.get("data") or {}
    if data.get("collection"):
        props["items"] = site.collections.get(data["collection"], [])
    if data.get("columns"):
        props["columns"] = data["columns"]
    if rendered.get("states"):
        props["states"] = rendered["states"]
    return props


def _surface_default(component: str) -> str | None:
    """The background a section takes when its content names none, or None for sections without a surface."""
    model = SECTION_PROPS.get(component)
    if model is None or not issubclass(model, Surface):
        return None
    return model.model_fields["background"].default


def alternate_backgrounds(sections: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Story 20.2, `rhythm: "alternate"`: content sections that name no background take the page colour or the
    muted tone, the opposite of the section before them; the first section (usually the hero) keeps its own."""
    out = []
    previous: str | None = None
    for index, section in enumerate(sections):
        content = section.get("content") or {}
        default = _surface_default(section["component"])
        if index > 0 and default == "default" and "background" not in content:
            background = "muted" if previous == "default" else "default"
            section = {**section, "content": {**content, "background": background}}
        if default is not None:
            previous = (section.get("content") or {}).get("background", default)
        out.append(section)
    return out


def color_roles(sections: list[dict[str, Any]], color_area: str | None) -> list[dict[str, Any]]:
    """Story 20.3, `theme.colorArea`: how much of a page carries the primary colour, on the page's top-level
    sections that name no background. minimal: call-to-action panels turn muted (colour stays on buttons); block:
    one anchor section in the primary colour (the first call to action, else the last content section; none when
    the spec already puts a section on it) and any other call to action muted; bold: block, and the hero takes the
    primary colour too."""
    if color_area not in ("minimal", "block", "bold"):
        return sections

    def free(index: int) -> bool:
        section = sections[index]
        return _surface_default(section["component"]) is not None and "background" not in (section.get("content") or {})

    def setting(index: int, background: str) -> None:
        sections[index] = {
            **sections[index],
            "content": {**(sections[index].get("content") or {}), "background": background},
        }

    sections = list(sections)
    ctas = [i for i, section in enumerate(sections) if section["component"] == "CallToAction" and free(i)]
    if color_area == "minimal":
        for index in ctas:
            setting(index, "muted")
        return sections
    content = [i for i, section in enumerate(sections) if section["component"] != "Hero" and free(i)]
    named = any(
        section["component"] != "Hero" and (section.get("content") or {}).get("background") == "primary"
        for section in sections
    )  # a section the spec already puts on the primary colour is the page's anchor
    anchor = None if named else ctas[0] if ctas else (content[-1] if content else None)
    for index in ctas:
        if index != anchor:
            setting(index, "muted")
    if anchor is not None:
        setting(anchor, "primary")
    if color_area == "bold":
        hero = next((i for i, section in enumerate(sections) if section["component"] == "Hero" and free(i)), None)
        if hero is not None:
            setting(hero, "primary")
    return sections


def _page(site: "_Site", route: dict[str, Any], color_area: str | None = None) -> dict[str, Any]:
    sections = color_roles([site.section(section) for section in route["sections"]], color_area)
    rhythm = route.get("rhythm", "uniform")
    if rhythm == "alternate":
        sections = alternate_backgrounds(sections)
    page: dict[str, Any] = {"title": route["title"], "sections": sections}
    if rhythm != "uniform":
        page["rhythm"] = rhythm
    if route.get("tree"):  # Epic 21: a designed page; its sections (if any) are only its content outline
        from src.modules.shared.domain.frontend_spec.trees import scope_css

        page["tree"] = site.tree(route["tree"])
        if route.get("css"):
            page["css"] = scope_css(route["css"], route["pageId"])  # idempotent: a drafted spec is scoped already
    return page


def tree_site(
    tree: dict[str, Any],
    spec: dict[str, Any],
    contract: dict[str, Any] | None,
    pages: dict[str, str],
    icon_set: str,
    section_renderer: Any = None,
) -> dict[str, Any]:
    """A checked tree as `site.json` carries it: every node gets a `kind` (`TreeRenderer.tsx` renders by it), images
    become asset nodes, icons are resolved to the site's set, `Link` targets to routes, library sections keep
    their content, and data components get their `binding` (`tree_bindings.bind_tree`)."""
    from src.modules.shared.domain.frontend_spec.icons import resolve_icon
    from src.modules.shared.domain.frontend_spec.tree_bindings import bind_tree
    from src.modules.shared.domain.frontend_spec.trees import classify

    tree = copy.deepcopy(tree)
    collections = [item["collection"] for item in spec.get("content") or []]
    bind_tree(tree, collections, pages)
    counter = [0]

    def convert(node: Any, root: bool = False) -> Any:
        if isinstance(node, str):
            return node
        node_type = str(node.get("type"))
        if root and node_type == "main":
            node_type = "div"  # the shell already renders the page inside <main>
        props = dict(node.get("props") or {})
        kind = classify(node_type)
        out: dict[str, Any] = {"kind": kind, "type": node_type}
        children = [convert(child) for child in node.get("children") or []]
        if node_type == "img" and isinstance(props.get("src"), str):
            out["kind"] = "image"
            out["asset"] = props.pop("src").removeprefix("asset:")
            props.pop("alt", None)
        elif kind == "icon":
            out["icon"] = resolve_icon(f"lucide:{node_type}", icon_set) or f"lucide:{node_type}"
        elif node_type == "Link":
            out["kind"] = "link"
            target = props.pop("to", None) or props.pop("href", None)
            if isinstance(target, str) and target.startswith("page:"):
                props["href"] = pages.get(target[5:], "/")
            elif isinstance(target, str):
                props["href"] = target
                props["external"] = target.startswith("http")
        elif kind == "section":
            # A library section inside a tree: its props are the section's content, plus an optional `data`
            # binding and `form`, rendered exactly like a page section (bindings, columns, record links).
            counter[0] += 1
            data = props.pop("data", None)
            form = props.pop("form", None)
            section: dict[str, Any] = {
                "id": str(props.pop("id", "")) or f"{node_type.lower()}-{counter[0]}",
                "component": node_type,
                "content": props,
            }
            if isinstance(data, dict):
                kind_of = "operation" if data.get("operationId") else "content" if data.get("collection") else None
                if kind_of:
                    section["data"] = {"kind": kind_of, **data}
            if isinstance(form, str):
                section["form"] = form
            rendered = (
                section_renderer(section)
                if section_renderer
                else {**section, "content": resolve_icons(props, icon_set)}
            )
            out.update({k: v for k, v in rendered.items() if k != "children"})
            props = {}
            children = []
        elif kind == "data":
            out["component"] = node_type
            if node.get("binding"):
                out["binding"] = node["binding"]
        if props:
            out["props"] = props
        if children:
            out["children"] = children
        return out

    return convert(tree, root=True)


def site_data(plan: dict[str, Any], spec: dict[str, Any], contract: dict[str, Any] | None = None) -> dict[str, Any]:
    site = _Site(plan, spec, contract)
    color_area = (spec.get("theme") or {}).get("colorArea")
    data = {
        "pages": {route["pageId"]: _page(site, route, color_area) for route in plan["routes"]},
        "collections": site.collections,
        "forms": {form["id"]: _form(form) for form in plan["forms"]},
    }
    layout = spec.get("layout") or {}
    for key in ("chrome", "footerTree"):  # Epic 21: designed chrome and footer
        if isinstance(layout.get(key), dict):
            data[key] = site.tree(layout[key])
    motion = (spec.get("theme") or {}).get("motion") or {}
    if motion.get("feel", "none") != "none":  # Story 20.6; a still site's site.json is unchanged
        data["motion"] = {"feel": motion["feel"], "signature": motion.get("signature") or "none"}
    return data


def site_json(plan: dict[str, Any], spec: dict[str, Any], contract: dict[str, Any] | None = None) -> str:
    return json.dumps(site_data(plan, spec, contract), indent=2, ensure_ascii=False) + "\n"


def _used_icons(value: Any) -> set[str]:
    if isinstance(value, dict):
        found = {value["icon"]} if isinstance(value.get("icon"), str) else set()
        return found.union(*(_used_icons(item) for item in value.values()))
    if isinstance(value, list):
        return set().union(*(_used_icons(item) for item in value))
    return set()


def _icon_import(ref: str) -> tuple[str, str]:
    """(identifier, import line) for one icon, imported on its own so a site bundles only the icons it uses."""
    icon_set, _, name = ref.partition(":")
    if icon_set == "phosphor":
        return (
            f"Phosphor{name}",
            f'import {{ {name} as Phosphor{name} }} from "@phosphor-icons/react/dist/ssr/{name}";\n',
        )
    return f"Lucide{name}", f'import Lucide{name} from "lucide-react/icons/{lucide_files()[name]}";\n'


def icons_ts(data: dict[str, Any], spec: dict[str, Any]) -> str:
    """The site's icon style and a component for every icon its content uses, plus the library's marks (checks,
    contact details) in the site's set (Lucide when the set is `none`)."""
    style = icon_style(spec)
    glyph_set = "phosphor" if style["set"] == "phosphor" else "lucide"
    refs = sorted(_used_icons(data)) if style["set"] != "none" else []
    marks = {name: f"{glyph_set}:{glyph(name, style['set'])}" for name in GLYPHS}
    imports: dict[str, str] = {}
    for ref in [*refs, *marks.values()]:
        identifier, line = _icon_import(ref)
        imports[identifier] = line
    ids = {ref: _icon_import(ref)[0] for ref in [*refs, *marks.values()]}
    icon_entries = "".join(f"  {json.dumps(ref)}: {ids[ref]} as unknown as TIconComponent,\n" for ref in refs)
    glyph_entries = "".join(f"  {name}: {ids[ref]} as unknown as TIconComponent,\n" for name, ref in marks.items())
    glyph_names = " | ".join(json.dumps(name) for name in GLYPHS)
    return (
        HEADER
        + 'import type { ComponentType } from "react";\n'
        + "".join(imports[key] for key in sorted(imports))
        + "\nexport type TIconComponent = ComponentType<Record<string, unknown>>;\n"
        + f"export type TGlyph = {glyph_names};\n"
        + "export type TIconStyle = {\n"
        + '  set: "lucide" | "phosphor" | "none";\n'
        + '  weight: "thin" | "light" | "regular" | "bold" | "fill" | "duotone";\n'
        + '  treatment: "plain" | "tile";\n'
        + "};\n\n"
        + "/** The site's content icons (Story 20.5): set, weight and treatment from `theme.icons`. */\n"
        + f"export const iconStyle: TIconStyle = {json.dumps(style)};\n\n"
        + "/** The set the library's own marks are drawn in (Lucide when the site has no content icons). */\n"
        + f'export const glyphSet: "lucide" | "phosphor" = {json.dumps(glyph_set)};\n\n'
        + "/** The icons this site's content uses, by resolved reference. */\n"
        + f"export const icons: Record<string, TIconComponent> = {{\n{icon_entries}}};\n\n"
        + f"export const glyphs: Record<TGlyph, TIconComponent> = {{\n{glyph_entries}}};\n"
    )


def used_sections(plan: dict[str, Any]) -> list[str]:
    from src.modules.shared.domain.frontend_spec.trees import classify, walk

    used = {section["component"] for route in plan["routes"] for section in iter_sections(route["sections"])}
    for route in plan["routes"]:  # Epic 21: library sections inside designed pages
        for node, _, _ in walk(route.get("tree")):
            if classify(str(node.get("type"))) == "section":
                used.add(str(node["type"]))
    if plan.get("trees"):
        used.add("Form")  # the tree renderer's RecordForm renders through the Form section
    return sorted(used)


def library_sections(plan: dict[str, Any], resolved: bool = False) -> set[str]:
    """The library sections a site needs: the built-ins it uses and its custom components' fallbacks (all of them,
    or with `resolved`, only those of components that did fall back)."""
    custom = plan.get("customComponents") or {}
    fallbacks = {entry["fallback"] for entry in custom.values() if not (resolved and entry.get("file"))}
    return (set(used_sections(plan)) - set(custom)) | fallbacks


def registry_ts(plan: dict[str, Any]) -> str:
    """Component name → implementation: a library section, or a custom component's generated file (17.3)."""
    custom = plan.get("customComponents") or {}
    names = sorted(library_sections(plan, resolved=True))
    imports = "".join(f'import {{ {name} }} from "@/components/sections/{name}";\n' for name in names)
    targets = {}
    for name in used_sections(plan):
        entry = custom.get(name)
        if entry and entry.get("file"):
            module = entry["file"].removeprefix("src/").removesuffix(".tsx")
            imports += f'import {name}Custom from "@/{module}";\n'
            targets[name] = f"{name}Custom"
        else:
            targets[name] = entry["fallback"] if entry else name
    entries = "".join(f"  {name}: {target} as unknown as TSectionComponent,\n" for name, target in targets.items())
    return (
        HEADER
        + 'import type { ComponentType, ReactNode } from "react";\n'
        + imports
        + "\nexport type TSectionComponent = ComponentType<Record<string, unknown> & { children?: ReactNode }>;\n\n"
        + "/** The sections this site uses, by FrontendSpec component name. */\n"
        + f"export const sections: Record<string, TSectionComponent> = {{\n{entries}}};\n"
    )


def _ts_name(name: str) -> str:
    return f"T{name.removesuffix('Props')}Content" if name.endswith("Props") else f"T{name}"


def _ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return _ts_name(schema["$ref"].rsplit("/", 1)[-1])
    if "anyOf" in schema:
        parts = [_ts(option) for option in schema["anyOf"] if option.get("type") != "null"]
        return " | ".join(dict.fromkeys(parts))
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        item = _ts(schema.get("items") or {})
        return f"({item})[]" if " | " in item else f"{item}[]"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}.get(
        kind, "Record<string, unknown>"
    )


def section_props_ts() -> str:
    """TypeScript for every section content model (Story 17.1): `T<Section>Content`, `T<Item>`, `TCta`."""
    blocks = []
    for name, schema in sorted(section_props_schemas().items()):
        required = set(schema.get("required") or [])
        fields = "".join(
            f"  {key}{'' if key in required else '?'}: {_ts(prop)};\n"
            for key, prop in (schema.get("properties") or {}).items()
        )
        blocks.append(f"export type {_ts_name(name)} = {{\n{fields}}};\n")
    return HEADER + "\n" + "\n".join(blocks)


def route_page(route: dict[str, Any]) -> str:
    seo = route.get("seo") or {}
    metadata = {"title": seo.get("title") or route["title"]}
    if seo.get("description"):
        metadata["description"] = seo["description"]
    return (
        HEADER
        + 'import type { Metadata } from "next";\n'
        + 'import { PageRenderer } from "@/components/renderer/PageRenderer";\n\n'
        + f"export const metadata: Metadata = {json.dumps(metadata, ensure_ascii=False)};\n\n"
        + f"export default function {to_pascal(route['pageId'].replace('-', '_'))}Page() {{\n"
        + f"  return <PageRenderer pageId={json.dumps(route['pageId'])} />;\n"
        + "}\n"
    )


def renderer_files(plan: dict[str, Any], spec: dict[str, Any], contract: dict[str, Any] | None) -> dict[str, str]:
    data = site_data(plan, spec, contract)
    files = {
        SITE_FILE: json.dumps(data, indent=2, ensure_ascii=False) + "\n",
        ICONS_FILE: icons_ts(data, spec),
        REGISTRY_FILE: registry_ts(plan),
        TYPES_FILE: section_props_ts(),
        FORM_SCHEMAS_FILE: form_schemas_ts(plan),
    }
    for route in plan["routes"]:
        files[route["file"]] = route_page(route)
    return files


def form_schemas_ts(plan: dict[str, Any]) -> str:
    """form id → its generated Zod schema and defaults (`src/lib/forms.ts`), for the library's Form section."""
    entries = "".join(
        f"  {json.dumps(form['id'])}: {{ schema: {form['schema']}, defaults: {to_camel(form['id'])}Defaults }},\n"
        for form in plan["forms"]
    )
    names = sorted(name for form in plan["forms"] for name in (form["schema"], f"{to_camel(form['id'])}Defaults"))
    imports = f'import {{ {", ".join(names)} }} from "@/lib/forms";\n' if names else ""
    return (
        HEADER
        + 'import type { ZodType } from "zod";\n'
        + imports
        + "\nexport type TFormSchema = { schema: ZodType; defaults: Record<string, unknown> };\n\n"
        + f"export const formSchemas: Record<string, TFormSchema> = {{\n{entries}}};\n"
    )


def library_primitives(plan: dict[str, Any], library: Path = LIBRARY_ROOT) -> set[str]:
    """The shadcn primitives the library files of this site import (its shell and the sections it uses)."""
    wanted: set[str] = set()
    for source in library_files(plan, [p.relative_to(library).as_posix() for p in library.rglob("*.ts*")]).values():
        wanted |= set(_UI_IMPORT.findall((library / source).read_text()))
    return wanted


def library_files(plan: dict[str, Any], available: list[str]) -> dict[str, str]:
    """target → source for the library files a site needs: its sections, the shared helpers (every file that is not
    a section) and its shell (`SiteShell.<shell>.tsx` is copied as `SiteShell.tsx`)."""
    used = library_sections(plan)
    shell = (plan.get("shell") or {}).get("shell", "header-footer")
    files: dict[str, str] = {}
    for relative in sorted(available):
        directory, _, name = relative.rpartition("/")
        stem, _, variant = name.removesuffix(".tsx").removesuffix(".ts").partition(".")
        if relative == TREE_STUB:
            if not plan.get("trees"):  # the renderer and the shell import it whether the site has trees or not
                files[f"{TREE_DIR}/TreeRenderer.tsx"] = relative
            continue
        if relative.startswith(f"{TREE_DIR}/") and not plan.get("trees"):
            continue  # Epic 21: the tree renderer and its primitives only for sites with designed pages
        if stem == "SiteShell":
            if variant == shell or (not variant and f"{directory}/SiteShell.{shell}.tsx" not in available):
                files[f"{directory}/SiteShell.tsx"] = relative
        elif not relative.startswith(f"{LIBRARY_DIR}/") or stem in used or stem not in BUILTIN_SECTIONS:
            files[relative] = relative
    return files
