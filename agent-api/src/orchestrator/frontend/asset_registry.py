"""The asset registry of a generated frontend (Story 15.1): `src/assets/index.ts`, asset id → render mode, alt,
aspect ratio, and the component or file. Pure codegen from the plan, owned by the generator (frontend_assets.py
rewrites it once the drawings exist)."""

import json
from typing import Any

from .planner import asset_component

ASSETS_FILE = "src/assets/index.ts"
HEADER = "// Generated by the Fullstack Generation Agent from the FrontendSpec assets. Do not edit.\n"


def _effective_mode(asset: dict[str, Any]) -> str:
    mode = asset["render"]
    if mode in ("video-embed", "video-file") and not asset.get("video"):
        return "placeholder"
    if mode == "svg-component" and not asset.get("drawn"):
        return "placeholder"
    if mode == "photo":
        return "public-file" if asset.get("generated") and asset.get("src") else "placeholder"
    if mode == "public-file" and not asset.get("src"):
        return "placeholder"
    return mode


def assets_ts(plan: dict[str, Any]) -> str:
    imports: list[str] = []
    icons: set[str] = set()
    entries = []
    credited = False
    for asset in plan.get("assets", []):
        mode = _effective_mode(asset)
        fields: dict[str, Any] = {"mode": mode, "aspectRatio": asset["aspectRatio"]}
        if asset.get("alt"):
            fields["alt"] = asset["alt"]
        if asset.get("decorative"):
            fields["decorative"] = True
        component = None
        if mode == "svg-component":
            component = asset_component(asset["id"])
            imports.append(f'import {component} from "@/components/assets/generated/{component}";\n')
        elif mode == "icon":
            component = asset["icon"]
            icons.add(component)
        elif mode == "public-file":
            fields |= {"src": asset["src"], "width": asset.get("width"), "height": asset.get("height")}
        elif mode == "remote":
            fields["src"] = asset["url"]
            if asset.get("credit"):  # Epic 27: "Photo by <name> on Unsplash"
                credited = True
                credit = asset["credit"]
                fields["credit"] = {key: credit[key] for key in ("name", "profileUrl", "sourceUrl") if credit.get(key)}
        elif mode in (
            "video-embed",
            "video-file",
        ):  # Epic 31: the provider's hit, played by VideoEmbed / BackgroundVideo
            video = dict(asset["video"])
            if asset.get("posterFile"):
                video["poster"] = "/" + asset["posterFile"].removeprefix("public/")
            fields["video"] = video
            if asset.get("credit"):
                credited = True
                credit = asset["credit"]
                keys = ("provider", "name", "profileUrl", "sourceUrl", "title")
                fields["credit"] = {key: credit[key] for key in keys if credit.get(key)}
        body = ", ".join(f"{key}: {json.dumps(value, ensure_ascii=False)}" for key, value in fields.items())
        if component:
            body += f", component: {component}"
        entries.append(f"  {json.dumps(asset['id'])}: {{ {body} }},\n")
    lucide = f'import {{ {", ".join(sorted(icons))} }} from "lucide-react";\n' if icons else ""
    # Epic 27: only a registry with a credited photo declares it (other sites' registries stay byte-identical)
    videos = any(_effective_mode(asset) in ("video-embed", "video-file") for asset in plan.get("assets", []))
    credit_type = (  # Epic 31 widens it only when a video is credited (photo-only registries stay as before)
        "  credit?: { provider?: string; name: string; profileUrl: string; sourceUrl: string; title?: string };\n"
        if videos
        else "  credit?: { name: string; profileUrl: string; sourceUrl: string };\n"
    )
    video_type = (
        '  video?: { provider: "youtube" | "pixabay"; id: string; title?: string; url?: string; poster?: string; '
        "width?: number; height?: number; duration?: number };\n"
    )
    return (
        HEADER
        + 'import type { ComponentType } from "react";\n'
        + lucide
        + "".join(imports)
        + '\nexport type TAssetMode = "svg-component" | "public-file" | "remote" | "icon" | "placeholder"'
        + (' | "video-embed" | "video-file"' if videos else "")
        + ";\n\n"
        + "export type TAsset = {\n"
        + "  mode: TAssetMode;\n  aspectRatio: string;\n  alt?: string;\n  decorative?: boolean;\n"
        + "  src?: string;\n  width?: number;\n  height?: number;\n"
        + "  component?: ComponentType<{ className?: string }>;\n"
        + (credit_type if credited else "")
        + (video_type if videos else "")
        + "};\n\n"
        + f"export const assets: Record<string, TAsset> = {{\n{''.join(entries)}}};\n"
    )


def external_images_note(plan: dict[str, Any]) -> str:
    """The generated README's list of linked images and videos (they are not part of the project)."""
    remote = [asset for asset in plan.get("assets", []) if asset["render"] == "remote"]
    videos = [
        asset
        for asset in plan.get("assets", [])
        if asset["render"] in ("video-embed", "video-file") and asset.get("video")
    ]
    if not remote and not videos:
        return ""
    lines: list[str] = []
    if remote:
        lines += [
            "",
            "Linked images (loaded from other sites, not part of this project; check they stay available):",
            "",
        ]
        lines += [
            f"- `{asset['id']}`: {asset['url']}"
            + (
                f" (photo by {asset['credit']['name']} on Unsplash, {asset['credit']['profileUrl']})"
                if asset.get("credit")
                else ""
            )
            for asset in remote
        ]
    if videos:  # Epic 31 (D5): every video with its title or description, its author or channel and a link
        lines += [
            "",
            "Videos (embedded or linked from their providers, not part of this project; credited on the page):",
            "",
        ]
        for asset in videos:
            video, credit = asset["video"], asset.get("credit") or {}
            who = f"{credit.get('name', '')} on {'YouTube' if video['provider'] == 'youtube' else 'Pixabay'}"
            link = credit.get("sourceUrl") or video.get("url") or ""
            lines.append(f"- `{asset['id']}`: {video.get('title') or asset.get('alt') or asset['id']} ({who}, {link})")
    return "\n".join(lines) + "\n"
