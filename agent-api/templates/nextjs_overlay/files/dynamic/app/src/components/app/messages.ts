const MESSAGES: Record<string, Record<TKey, string>> = { en, ja };

/** The kit's text for `key` in the app's language, `{name}`-style values filled in. */
export function t(key: TKey, values: Record<string, string | number> = {}): string {
  const table = MESSAGES[(app.locale ?? "en").split("-")[0]] ?? en;
  return (table[key] ?? en[key]).replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}

/** Japanese has no plural or case: a plural label stays as written; English lowercases it inside a sentence. */
export function inSentence(label: string): string {
  return (app.locale ?? "en").startsWith("ja") ? label : label.toLowerCase();
}
